    def generate_batch(
        self,
        workspace: Workspace,
        file_paths: list[str]
    ) -> dict[str, str]:

        generated_files = {}

        print(
            f"\n=== GENERATING {len(file_paths)} FILE(S) "
            f"INDIVIDUALLY ==="
        )

        for index, file_path in enumerate(
            file_paths,
            start=1
        ):

            print(
                f"\n--- FILE {index}/{len(file_paths)} ---"
            )

            print(
                f"Generating: {file_path}"
            )

            last_error = None

            for attempt in range(1, 4):

                try:

                    code = self.generate_file(
                        workspace,
                        file_path
                    )

                    if not code or not code.strip():
                        raise ValueError(
                            "LLM returned empty code."
                        )

                    generated_files[file_path] = code

                    print(
                        f"Generated: {file_path}"
                    )

                    break

                except Exception as error:

                    last_error = error

                    print(
                        f"Generation failed for "
                        f"{file_path}"
                    )

                    print(
                        f"Attempt {attempt}/3"
                    )

                    print(
                        f"Error: {error}"
                    )

                    if attempt == 3:
                        raise RuntimeError(
                            f"Failed to generate "
                            f"'{file_path}' after "
                            f"3 attempts."
                        ) from error

            if file_path not in generated_files:
                raise RuntimeError(
                    f"File generation failed: "
                    f"{file_path}. "
                    f"Last error: {last_error}"
                )

            workspace.files[file_path] = (
                generated_files[file_path]
            )

        return generated_files

    def _get_available_files(
        self,
        workspace: Workspace,
        current_file: str
    ) -> str:

        paths = list(
            workspace.blueprint.files
        )

        if current_file not in paths:
            paths.append(current_file)

        return "\n".join(
            f"- {path}"
            for path in paths
        )

    def _get_relevant_files(
        self,
        workspace: Workspace,
        current_file: str
    ) -> list[str]:

        relevant = []

        if current_file.startswith(
            "src/components/"
        ):

            priority = [
                "src/App.jsx",
                "src/router.jsx",
                "src/index.css",
            ]

            for path in priority:
                if path in workspace.files:
                    relevant.append(path)

        elif current_file.startswith(
            "src/pages/"
        ):

            priority = [
                "src/App.jsx",
                "src/router.jsx",
            ]

            for path in priority:
                if path in workspace.files:
                    relevant.append(path)

            component_files = [
                path
                for path in workspace.files
                if path.startswith(
                    "src/components/"
                )
            ]

            relevant.extend(
                component_files
            )

        elif current_file == "src/App.jsx":

            component_files = [
                path
                for path in workspace.files
                if path.startswith(
                    "src/components/"
                )
            ]

            relevant.extend(
                component_files
            )

        return relevant